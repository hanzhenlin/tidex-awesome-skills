#!/usr/bin/env python3
"""Add a text-defined visual style after a square representative image is available."""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

from style_library_import import (
    create_style_assets,
    get_next_style_number,
    rebuild_and_validate,
    update_manifest,
    update_markdown_source,
    update_model_capabilities,
    update_readme_and_skill,
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-name", help="Chinese/original style label; optional for a text-only original style")
    parser.add_argument("--generation-name", help="English generation style name; optional for a text-only original style")
    parser.add_argument("--traits", default="", help="Positive concrete visual traits")
    parser.add_argument("--traits-file", type=Path, help="File containing traits text")
    parser.add_argument("--raw-traits", action="store_true", help="Preserve traits exactly as provided without positive_traits filtering")
    parser.add_argument("--image", type=Path, help="Representative source image, supplied or generated by the Skill")
    parser.add_argument("--dry-run", action="store_true", help="Print the resolved registration policy without modifying the library")
    return parser.parse_args()


def positive_traits(value: str) -> str:
    """Keep only concrete positive traits for both metadata and prompting, stripping forbidden demo subject content."""
    subject_leakage_patterns = [
        r"[白黑红黄蓝绿米粉]\S*?(?:长裙|短裙|连衣裙|衬衫|风衣|T恤|衣服|背带裤)",
        r"[黑金黄棕白]\S*?(?:短发|长发|马尾|卷发|发型)",
        r"(?:侧身|回眸|侧脸|站姿|坐姿|奔跑|漫步|蹲下|招手)的?(?:自然)?(?:姿态|姿势|动态)?",
        r"大面积\S*?(?:花田|花海|草地|植被|向日葵)",
        r"(?:海湾|湖海|山峦|雪山|街道|马路|森林)\S*?(?:远景|中景|近景|层次)",
        r"前景\S*?(?:轻微遮挡|虚化遮挡|花草遮挡)",
        r"三分法构图人物偏[左右中]",
        r"年轻[男女]性|年轻[男女]子",
    ]
    leakage_re = re.compile("|".join(subject_leakage_patterns))

    parts = [part.strip() for part in value.replace("。", "；").split("；")]
    cleaned = []
    for part in parts:
        if not part:
            continue
        sub_clauses = re.split(r"[,，、]", part)
        valid_sub = []
        for sub in sub_clauses:
            s = sub.strip()
            if not s:
                continue
            for marker in ("避免", "不要", "不准", "禁止"):
                if marker in s:
                    s = s.split(marker, 1)[0]
            s = re.sub(r"无(?:写实纹理|精细材质|真实纹理)[、，]?", "", s).strip("、， ")
            if not s:
                continue
            if leakage_re.search(s):
                print(f"[GUARD] 拦截示意图具体画面内容污染: {s}")
                continue
            valid_sub.append(s)
        if valid_sub:
            cleaned.append("、".join(valid_sub))
    return "；".join(cleaned)


def registration(args: argparse.Namespace, number: str) -> dict[str, str | bool]:
    raw_text = args.traits_file.read_text(encoding="utf-8") if args.traits_file and args.traits_file.is_file() else args.traits
    if not (args.source_name or raw_text.strip()):
        raise ValueError("IMAGE_ONLY: image-only style imports belong to Tweet Style Importer.")
    traits = " ".join(raw_text.split()) if args.raw_traits else positive_traits(raw_text)
    return {
        "number": number,
        "source_name": args.source_name or "自创文本定义风格",
        "generation_name": args.generation_name or args.source_name or f"Original Text-Defined Style {number}",
        "traits": traits,
        "name_activation": "weak" if traits else "strong",
        "traits_activation": "strong" if traits else "none",
        "use_reference_image": False,
    }


def main() -> None:
    args = parse_args()
    number = get_next_style_number()
    try:
        record = registration(args, number)
    except ValueError as error:
        raise SystemExit(str(error)) from error
    if args.dry_run:
        print(json.dumps(record, ensure_ascii=False))
        return
    if not args.image:
        raise SystemExit("A representative image is required. Generate one 1:1 image first, then rerun with --image.")
    if not args.image.is_file():
        raise SystemExit(f"Representative image does not exist: {args.image}")

    assets = create_style_assets(number, [args.image])
    update_markdown_source(number, str(record["source_name"]), str(record["generation_name"]), str(record["traits"]))
    update_model_capabilities(number, name_activation=str(record["name_activation"]),
                              traits_activation=str(record["traits_activation"]))
    update_readme_and_skill(number)
    update_manifest(number)
    rebuild_and_validate()

    print(json.dumps({
        **record,
        "single_path": str(assets["tile"]),
        "grid_path": str(assets["grid"]) if assets["grid"] else None,
        "sheet_path": str(assets["sheet"]),
    }, ensure_ascii=False))


if __name__ == "__main__":
    main()
